type Props = {
  name?: string;
  className?: string;
  size?: number;
  strokeWidth?: number;
};

export default function Icon({ name, className, size = 20, strokeWidth = 1.8 }: Props) {
  if (!name) return null;
  const key = name.toLowerCase().trim();

  if (brandPaths[key]) {
    return (
      <svg
        viewBox="0 0 24 24"
        width={size}
        height={size}
        fill="currentColor"
        aria-hidden="true"
        className={cn('shrink-0', className)}
        style={{ width: size, height: size }}
      >
        <path d={brandPaths[key]} />
      </svg>
    );
  }

  const lucideName = (iconNames.includes(key as never) ? key : 'sparkles') as never;

  return (
    <span
      className={cn('inline-flex shrink-0 items-center justify-center', className)}
      style={{ width: size, height: size }}
      aria-hidden="true"
    >
      {/* className goes on the svg as well, so fill and stroke utilities apply to it */}
      <DynamicIcon name={lucideName} size={size} strokeWidth={strokeWidth} className={className} />
    </span>
  );
}
